#!/usr/bin/env bash
#
# Installer for the Vault CLI (macOS / Linux).
#
# Generates a small `vault` launcher on your PATH that runs the VaultENV
# Python interpreter against src/vault.py, and always changes into src/ first
# so payloads and the log file resolve correctly regardless of where you call
# `vault` from.
#
# Also installs the man page (docs/vault.1) under PREFIX/share/man unless
# --no-man is given.
#
# Usage:
#   ./install.sh                    # install to ~/.local/bin as `vault`
#   PREFIX=/usr/local ./install.sh  # install to /usr/local/bin
#   ./install.sh --prefix ~/bin --name vault-scan
#   ./install.sh --no-man           # install without the man page
#   ./install.sh --uninstall        # remove the installed launcher + man page
#
# Overrides (env or args): --prefix/--name/--python

set -euo pipefail

# Resolve the repository root (directory containing this script).
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC_DIR="$REPO_DIR/src"

if [[ ! -f "$SRC_DIR/vault.py" ]]; then
    echo "error: $SRC_DIR/vault.py not found" >&2
    exit 1
fi

# --- Argument / env parsing -------------------------------------------------
NAME="${VAULT_NAME:-vault}"
PREFIX="${VAULT_PREFIX:-}"
PYTHON="${VAULT_PYTHON:-}"
UNINSTALL=0
NO_MAN=0

while [[ $# -gt 0 ]]; do
    case "$1" in
        --name)       NAME="$2"; shift 2 ;;
        --prefix)     PREFIX="$2"; shift 2 ;;
        --python)     PYTHON="$2"; shift 2 ;;
        --uninstall)  UNINSTALL=1; shift ;;
        --no-man)     NO_MAN=1; shift ;;
        -h|--help)
            sed -n '3,20p' "$0" | sed 's/^# \{0,1\}//'
            exit 0 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
done

# Default install prefix: ~/.local/bin (user-writable and on PATH on macOS).
if [[ -z "$PREFIX" ]]; then
    if [[ -w /usr/local/bin ]]; then
        PREFIX="/usr/local"
    else
        PREFIX="$HOME/.local"
    fi
fi
BIN_DIR="$PREFIX/bin"
TARGET="$BIN_DIR/$NAME"
MAN_ROOT="$PREFIX/share/man"
MAN_DIR="$MAN_ROOT/man1"
MAN_TARGET="$MAN_DIR/$NAME.1"

if [[ "$UNINSTALL" -eq 1 ]]; then
    if [[ -e "$TARGET" ]]; then
        rm -f "$TARGET"
        echo "Removed $TARGET"
    else
        echo "$TARGET not installed" >&2
        exit 1
    fi
    if [[ -e "$MAN_TARGET" ]]; then
        rm -f "$MAN_TARGET"
        echo "Removed $MAN_TARGET"
    fi
    exit 0
fi

# --- Resolve the Python interpreter ----------------------------------------
if [[ -z "$PYTHON" ]]; then
    if command -v conda >/dev/null 2>&1; then
        # Prefer the VaultENV environment (last field is its path).
        PYTHON="$(conda env list 2>/dev/null \
            | awk '$1 == "VaultENV" { print $NF; exit }')"
        [[ -n "$PYTHON" ]] && PYTHON="$PYTHON/bin/python"
    fi
fi
[[ -z "$PYTHON" ]] && PYTHON="/opt/anaconda3/envs/VaultENV/bin/python"
# Final fallback: whatever python3 is on PATH (last resort).
if [[ ! -x "$PYTHON" ]]; then
    if command -v python3 >/dev/null 2>&1; then
        PYTHON="$(command -v python3)"
    else
        echo "error: could not locate a Python interpreter" >&2
        echo "       set VAULT_PYTHON=/path/to/python and retry" >&2
        exit 1
    fi
fi

# --- Sanity-check the environment ------------------------------------------
if ! "$PYTHON" -c 'import scapy, requests, bs4' >/dev/null 2>&1; then
    echo "warning: $PYTHON is missing dependencies (scapy/requests/bs4)." >&2
    echo "         install them with: $PYTHON -m pip install -r '$REPO_DIR/requirements.txt'" >&2
fi

# --- Emit the launcher ------------------------------------------------------
shell_quote() {  # wrap $1 in double quotes, escaping "$`\
    printf '"%s"' "$(printf '%s' "$1" | sed 's/[$`\\"]/\\&/g')"
}

mkdir -p "$BIN_DIR"
SRC_DIR_Q="$(shell_quote "$SRC_DIR")"
VAULT_PY_Q="$(shell_quote "$SRC_DIR/vault.py")"
PYTHON_Q="$(shell_quote "$PYTHON")"

cat > "$TARGET" <<EOF
#!/usr/bin/env bash
# Generated by install.sh ($REPO_DIR). Re-run install.sh to update.
cd $SRC_DIR_Q || { echo "\$0: cannot enter the Vault src/ directory" >&2; exit 1; }
exec $PYTHON_Q $VAULT_PY_Q "\$@"
EOF
chmod +x "$TARGET"

# --- Install the man page ---------------------------------------------------
MAN_INSTALLED=0
if [[ "$NO_MAN" -eq 0 ]]; then
    MAN_SRC="$REPO_DIR/docs/vault.1"
    if [[ ! -f "$MAN_SRC" ]]; then
        echo "warning: man page not found at $MAN_SRC; skipping." >&2
    else
        mkdir -p "$MAN_DIR"
        if [[ "$NAME" == "vault" ]]; then
            cp "$MAN_SRC" "$MAN_TARGET"
        else
            # Rename the .TH header to match the chosen command name.
            # (tr instead of ${NAME^^}: macOS ships bash 3.2, no ^^ expansion)
            NAME_UPPER="$(printf '%s' "$NAME" | tr '[:lower:]' '[:upper:]')"
            sed "1s/^\.TH VAULT/.TH $NAME_UPPER/" "$MAN_SRC" > "$MAN_TARGET"
        fi
        MAN_INSTALLED=1
    fi
fi

# --- Report ----------------------------------------------------------------
echo "Installed: $TARGET"
echo "  Python:  $PYTHON"
echo "  Source:  $SRC_DIR/vault.py"
if [[ "$MAN_INSTALLED" -eq 1 ]]; then
    echo "  Man page: $MAN_TARGET"
    case ":${MANPATH:-}:" in
        *":$MAN_ROOT:"*) ;;
        *) echo "  hint: $MAN_ROOT is not on your MANPATH."
           echo "        export MANPATH=\"$MAN_ROOT:\$MANPATH\"" ;;
    esac
fi

case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) echo "warning: $BIN_DIR is not on your PATH." >&2
       echo "         add: export PATH=\"$BIN_DIR:\$PATH\"" >&2 ;;
esac

echo
echo "Try it:  $NAME -h"
